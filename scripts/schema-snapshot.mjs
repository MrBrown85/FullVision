#!/usr/bin/env node
/*
 * The database's shape, kept in the repo so it can't drift from live.
 *
 * Runs scripts/schema-snapshot.sql (system catalogs only) against
 * DATABASE_URL with psql, as CI's read-only fv_schema_reader role, and
 * compares the answer with docs/schema.generated.sql. A difference fails
 * CI and writes the live snapshot to schema-snapshot.live.sql, which CI
 * uploads: commit it as docs/schema.generated.sql once the migration that
 * changed the database is in the PR.
 *
 *   node scripts/schema-snapshot.mjs           check (CI)
 *   node scripts/schema-snapshot.mjs --write   write docs/schema.generated.sql
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SQL = join(root, 'scripts', 'schema-snapshot.sql');
const COMMITTED = join(root, 'docs', 'schema.generated.sql');
const LIVE_OUT = join(root, 'schema-snapshot.live.sql');
const HEADER =
  '-- Generated by scripts/schema-snapshot.mjs from the live database (gradebook-prod).\n' +
  "-- Don't edit by hand: CI fails when this differs from live. schema.sql keeps the notes.\n\n";

export function snapshotText(raw) {
  return HEADER + raw.replace(/\s+$/, '') + '\n';
}

export function firstDifference(a, b) {
  const x = a.split('\n');
  const y = b.split('\n');
  for (let i = 0; i < Math.max(x.length, y.length); i++) {
    if (x[i] !== y[i]) return { line: i + 1, committed: x[i], live: y[i] };
  }
  return null;
}

function main() {
  const url = process.env.DATABASE_URL;
  if (!url) {
    console.error('DATABASE_URL is not set.');
    process.exit(2);
  }
  const raw = execFileSync('psql', [url, '-X', '-A', '-t', '-v', 'ON_ERROR_STOP=1', '-f', SQL], {
    encoding: 'utf-8',
    maxBuffer: 64 * 1024 * 1024,
  });
  const live = snapshotText(raw);
  if (process.argv.includes('--write')) {
    writeFileSync(COMMITTED, live);
    console.log('Wrote docs/schema.generated.sql');
    return;
  }
  const committed = existsSync(COMMITTED) ? readFileSync(COMMITTED, 'utf-8') : '';
  if (committed === live) {
    console.log('docs/schema.generated.sql matches the live database.');
    return;
  }
  writeFileSync(LIVE_OUT, live);
  const diff = firstDifference(committed, live);
  console.error('docs/schema.generated.sql does not match the live database.');
  if (diff)
    console.error(`First difference at line ${diff.line}:\n  committed: ${diff.committed}\n  live:      ${diff.live}`);
  console.error('The live snapshot is in the "schema-snapshot" artifact; commit it as docs/schema.generated.sql.');
  process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
