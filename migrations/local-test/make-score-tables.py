"""Write score-tables.sql (and bundle-tables.sql) from
docs/schema.generated.sql, the snapshot CI keeps equal to gradebook-prod.
Nothing is typed by hand: every column, constraint, index, trigger and
policy line is the snapshot's own.

  python3 make-score-tables.py > score-tables.sql
  python3 make-score-tables.py bundle > bundle-tables.sql

NEW tables are created whole. BASE tables (harness.sql makes them with a
few columns) only gain the columns and sync-cursor triggers they lack; their
constraints, indexes and policies stay the harness's.
score_rpcs.py checks the result against the snapshot, so a snapshot change
that touches one of these tables fails there until this is run again."""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SNAPSHOT = os.path.join(HERE, '..', '..', 'docs', 'schema.generated.sql')

# In dependency order: a table comes after every table its triggers and
# policies read. Foreign keys are added after all the tables exist.
NEW = ['course_sync_cursor', 'subject', 'competency_group', 'section', 'tag', 'category', 'module',
       'rubric', 'criterion', 'criterion_check', 'criterion_tag', 'rubric_tag', 'assessment',
       'assessment_tag', 'score', 'score_audit', 'tag_score', 'rubric_score', 'rubric_check_score']
BASE = ['course', 'student', 'enrollment']
# The other tables get_class_bundle reads, for bundle_created_at.py. Loaded
# after score-tables.sql and bundle-prelude.sql.
BUNDLE = ['custom_tag', 'report_config', 'observation_template', 'observation', 'observation_student',
          'observation_tag', 'observation_custom_tag', 'goal', 'reflection', 'note', 'section_override',
          'rubric_print', 'term_rating', 'term_rating_assessment', 'term_rating_growth_area',
          'term_rating_observation', 'term_rating_strength']
# observation_template's trigger calls a teacher-level sync function the
# harness does not load.
SKIP_TRIGGERS = {'teacher_sync_cursor_observation_template_student_records'}


def blocks(text):
    """{table: {'cols': [...], 'cons': [...], 'idx': [...], 'trg': [...], 'pol': [...]}}"""
    out, cur = {}, None
    for line in text.splitlines():
        m = re.match(r'table public\.(\w+)', line)
        if m:
            cur = out[m.group(1)] = {'cols': [], 'cons': [], 'idx': [], 'trg': [], 'pol': []}
            continue
        if line.startswith('table ') or line.startswith('function '):
            cur = None
            continue
        if cur is None or not line.strip():
            continue
        body = line[2:] if line.startswith('  ') else line
        if cur['pol'] and not line.startswith('  policy '):
            cur['pol'][-1] += '\n' + line  # a policy's expression runs over lines
        elif line.startswith('  policy '):
            cur['pol'].append(body)
        elif line.startswith('  constraint '):
            cur['cons'].append(body)
        elif re.match(r'  CREATE (UNIQUE )?INDEX ', line):
            cur['idx'].append(body)
        elif re.match(r'  CREATE (CONSTRAINT )?TRIGGER ', line):
            cur['trg'].append(body)
        else:
            cur['cols'].append(body)
    return out


def main():
    global NEW, BASE
    b = blocks(open(SNAPSHOT).read())
    w = sys.stdout.write
    if sys.argv[1:] == ['bundle']:
        NEW, BASE = BUNDLE, []
        w('-- GENERATED by make-score-tables.py bundle from docs/schema.generated.sql (the\n'
          '-- live snapshot). Do not edit: run the script again. Load after\n'
          '-- score-tables.sql and bundle-prelude.sql.\n\n')
    else:
        w('-- GENERATED by make-score-tables.py from docs/schema.generated.sql (the live\n'
          '-- snapshot). Do not edit: run the script again. Load after score-prelude.sql,\n'
          '-- which makes the functions these triggers and policies call.\n\n')
        w('-- Columns production has that harness.sql leaves out.\n')
    for t in BASE:
        for col in b[t]['cols']:
            w(f'alter table public.{t} add column if not exists {col};\n')
    w('\n')
    for t in NEW:
        w(f'create table public.{t} (\n  ' + ',\n  '.join(b[t]['cols']) + '\n);\n')
    w('\n-- Keys first, then the foreign keys that point at them.\n')
    for want_fk in (False, True):
        for t in NEW:
            for con in b[t]['cons']:
                name, definition = con[len('constraint '):].split(' ', 1)
                if definition.startswith('TRIGGER'):
                    continue  # a constraint trigger: made by its CREATE CONSTRAINT TRIGGER line
                if definition.startswith('FOREIGN KEY') == want_fk:
                    w(f'alter table public.{t} add constraint {name} {definition};\n')
    w('\n')
    for t in NEW:
        made = {c.split(' ')[1] for c in b[t]['cons']}
        for idx in b[t]['idx']:
            if re.match(r'CREATE (UNIQUE )?INDEX (\w+) ', idx).group(2) not in made:
                w(idx + ';\n')
    w('\n')
    for t in NEW + BASE:
        for trg in b[t]['trg']:
            if trg.split(' ')[2] not in SKIP_TRIGGERS:
                w(trg + ';\n')
    w('\n')
    for t in NEW:
        w(f'alter table public.{t} enable row level security;\n')
        for pol in b[t]['pol']:
            name, rest = pol[len('policy '):].split(' ', 1)
            w(f'create policy {name} on public.{t} {rest};\n')


if __name__ == '__main__':
    main()
