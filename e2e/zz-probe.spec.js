import { test, expect } from '@playwright/test';
test.use({ viewport: { width: 1280, height: 900 } });
test('probe', async ({ page }) => {
  page.on('pageerror', e => console.log('ERR', String(e)));
  await page.addInitScript(() => localStorage.setItem('fv-build-commentBank', '1'));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/login.html?demo=1');
  await page.waitForURL(/\/dashboard/, { timeout: 15000 });
  await page.waitForFunction(() => { var cid = getActiveCourse(); return !!cid && getAssessments(cid).some(a => a.id === 'sci8a1'); });
  await page.evaluate(() => { const cid = getActiveCourse(); Grader.setCriterionComment(cid, 'st2', 'sci8a1', 'crit_sci8_lab_inquiry', 'Name the variable you change before you start, and the data.'); });
  await page.goto('/assignments');
  await page.waitForSelector('#dock-mount nav');
  const card = page.locator('#ac-sci8a4');
  if (!(await card.evaluate(el => el.classList.contains('open')))) await card.locator('.assess-title').click();
  const row = card.locator('.rsg-criterion-row[data-student="st2"][data-criterion="crit_sci8_lab_inquiry"]');
  await row.scrollIntoViewIfNeeded();
  await row.locator('.rsg-level.l3').click();
  await row.locator('.rsg-crit-comment').click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'test-results/cb/probe1.png' });
  console.log(await row.locator('.rsg-crit-edit').evaluate(e => e.outerHTML.slice(0, 3000)));
});
