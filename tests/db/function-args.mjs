/*
 * How the security rule tests (tests/db/run.mjs) build the arguments for
 * each database function a signed-in teacher may call.
 *
 * Each id argument names a kind of row ('course', 'enrollment' and so on:
 * the keys rls_test.seed() answers with). A call is made once with teacher
 * A's own rows (the control), once with teacher B's rows everywhere, and,
 * when it takes more than one kind, once for each kind with only that one
 * swapped to B's. Arguments with a default are left out unless they name a
 * kind or are given below. Other arguments get a plain value of their type.
 *
 * In VALUES, `${kind}` stands for that kind's id, and each value is an SQL
 * expression. A value that is an object or an array is sent as jsonb.
 */

