/**
 * scripts/schema-snapshot.mjs keeps docs/schema.generated.sql in step with
 * the live database (CI runs it as fv_schema_reader). These cover the parts
 * that don't need a database.
 */
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { firstDifference, snapshotText } from '../scripts/schema-snapshot.mjs';

describe('schema snapshot', () => {
  it('heads the file and ends it with one newline, whatever psql printed', () => {
    const text = snapshotText('table public.course (rls on)\n  id uuid not null\n\n');
    expect(text.startsWith('-- Generated by scripts/schema-snapshot.mjs')).toBe(true);
    expect(text.endsWith('  id uuid not null\n')).toBe(true);
  });

  it('names the first line that differs', () => {
    expect(firstDifference('a\nb\nc', 'a\nB\nc')).toEqual({ line: 2, committed: 'b', live: 'B' });
    expect(firstDifference('a', 'a')).toBe(null);
  });

  it('reads only the system catalogs, so the read-only role sees what every role sees', () => {
    const sql = readFileSync(new URL('../scripts/schema-snapshot.sql', import.meta.url), 'utf-8');
    expect(sql).not.toMatch(/information_schema|has_\w+_privilege|current_user|session_user/);
  });
});
